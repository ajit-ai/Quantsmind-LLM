"""Agent workflow orchestration for TAKSH."""

from __future__ import annotations

import json
import time
from dataclasses import asdict, dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Callable

from taksh.engineering import (
    EngineeringTask,
    create_task,
    run_engineering_task,
    engineering_report,
)
from taksh.memory import ProjectMemory
from taksh.permissions import PermissionPolicy
from taksh.tools import ToolRuntime, build_engineering_tool_registry


class AgentState(str, Enum):
    CREATED = "CREATED"
    UNDERSTOOD = "UNDERSTOOD"
    PLANNED = "PLANNED"
    TOOLS_SELECTED = "TOOLS_SELECTED"
    GENERATED = "GENERATED"
    REVIEWED = "REVIEWED"
    APPROVED = "APPROVED"
    APPLIED = "APPLIED"
    VALIDATED = "VALIDATED"
    TESTED = "TESTED"
    REPAIRED = "REPAIRED"
    VERIFIED = "VERIFIED"
    REPORTED = "REPORTED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    BLOCKED = "BLOCKED"


@dataclass
class AgentTask:
    task_id: str
    objective: str
    root: str
    state: AgentState = AgentState.CREATED
    history: list[dict[str, Any]] = field(default_factory=list)
    provenance: dict[str, Any] = field(default_factory=dict)
    result: dict[str, Any] = field(default_factory=dict)
    cancelled: bool = False

    def transition(self, new_state: AgentState, detail: str = "") -> None:
        self.history.append({"from": self.state.value, "to": new_state.value, "detail": detail, "timestamp": time.time()})
        self.state = new_state

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class AgentWorkflow:
    def __init__(self, storage_path: str | Path | None = None, max_tool_calls: int = 100) -> None:
        self.memory = ProjectMemory(storage_path) if storage_path else None
        self.permissions = PermissionPolicy()
        self.registry = build_engineering_tool_registry()
        self.runtime = ToolRuntime(self.registry, self.permissions)
        self.runtime._max_calls = max_tool_calls

    def run(
        self,
        task_id: str,
        objective: str,
        root: str,
        provider: Any,
        *,
        apply: bool = False,
        validate: bool = True,
        run_tests_flag: bool = False,
        memory_project_id: str | None = None,
        timeout_seconds: float | None = None,
    ) -> AgentTask:
        start = time.time()
        agent_task = AgentTask(task_id=task_id, objective=objective, root=root)
        try:
            # UNDERSTAND
            from taksh.engineering import inspect_project

            context = inspect_project(root)
            agent_task.transition(AgentState.UNDERSTOOD, "project inspected")
            if self.memory and memory_project_id:
                self.memory.store(memory_project_id, "project_summary", context["summary"], source="inspect_project", verified=True)

            # PLAN
            eng_task = create_task(task_id, objective, root)
            eng_task, plan = __import__("taksh.engineering", fromlist=["plan_task"]).plan_task(eng_task, provider, context)
            if plan is None:
                agent_task.transition(AgentState.BLOCKED, "no plan generated")
                agent_task.result = eng_task.to_dict()
                return agent_task
            agent_task.transition(AgentState.PLANNED, f"{len(plan.changes)} changes")

            # SELECT TOOLS
            selected = ["inspect_project", "validate_project"]
            if apply:
                selected.append("patch_apply")
            if run_tests_flag:
                selected.append("test_execution")
            agent_task.transition(AgentState.TOOLS_SELECTED, ", ".join(selected))

            # GENERATE
            agent_task.transition(AgentState.GENERATED, "plan generated by provider")

            # REVIEW
            from taksh.engineering import review_plan

            review_plan(plan)
            agent_task.transition(AgentState.REVIEWED, "plan reviewed")

            # APPROVE
            if apply:
                agent_task.transition(AgentState.APPROVED, "mutation approved by workflow")
            else:
                agent_task.transition(AgentState.APPROVED, "read-only approval")

            # APPLY / VALIDATE / TEST
            eng_task = run_engineering_task(
                eng_task,
                provider,
                apply=apply,
                validate=validate,
                run_project_tests=run_tests_flag,
            )
            if eng_task.state.value == "APPLIED":
                agent_task.transition(AgentState.APPLIED, "changes applied")
            if eng_task.state.value in ("VALIDATED", "COMPLETED"):
                agent_task.transition(AgentState.VALIDATED, "validation passed")
            if run_tests_flag and eng_task.test_result:
                agent_task.transition(AgentState.TESTED, eng_task.test_result.get("status", "unknown"))
            if eng_task.state.value == "COMPLETED":
                agent_task.transition(AgentState.VERIFIED, "verification passed")
            elif eng_task.state.value == "FAILED":
                agent_task.transition(AgentState.FAILED, "task failed")

            # REPORT
            report = engineering_report(eng_task)
            agent_task.result = report
            agent_task.provenance = {
                "provider": getattr(provider, "name", None),
                "tool_calls": len(self.runtime.history),
                "duration_seconds": time.time() - start,
            }
            if eng_task.state.value == "COMPLETED":
                agent_task.transition(AgentState.REPORTED, "report generated")
            if self.memory and memory_project_id:
                self.memory.store(memory_project_id, "task_result", report, source="agent_workflow", verified=eng_task.state.value == "COMPLETED", tags=[task_id])
            return agent_task
        except Exception as exc:  # noqa: BLE001
            agent_task.transition(AgentState.FAILED, f"{type(exc).__name__}: {exc}")
            agent_task.result = {"error": str(exc)}
            return agent_task

    def cancel(self, agent_task: AgentTask) -> None:
        agent_task.cancelled = True
        agent_task.transition(AgentState.CANCELLED, "cancelled by user")

    def persist(self, agent_task: AgentTask, path: str | Path) -> None:
        Path(path).write_text(json.dumps(agent_task.to_dict(), indent=2), encoding="utf-8")

    def load(self, path: str | Path) -> AgentTask:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        task = AgentTask(**{k: v for k, v in data.items() if k in AgentTask.__dataclass_fields__})
        task.state = AgentState(data["state"])
        task.history = data.get("history", [])
        return task
