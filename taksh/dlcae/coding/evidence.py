"""Evidence categories for ENG3 coding-intelligence artifacts.

Categories are deliberately narrow and additive:

    MODEL_GENERATED   generated by a model — never verified by itself
    TOOL_OBSERVED     observed by a tool (lint, heuristic) — not verified
    TOOL_VERIFIED     verified by an independent tool/oracle verdict
    HUMAN_CONFIRMED   confirmed by an authorized human
    INFERRED          model/heuristic inference — weakest evidence
    CONFLICTED        conflicting evidence kept visible
    INVALIDATED       invalidated (source change or regression)

Only TOOL_VERIFIED and HUMAN_CONFIRMED may promote knowledge to VERIFIED;
INFERRED/MODEL_GENERATED never can.
"""

from __future__ import annotations

from enum import Enum


class EvidenceCategory(str, Enum):
    MODEL_GENERATED = "MODEL_GENERATED"
    TOOL_OBSERVED = "TOOL_OBSERVED"
    TOOL_VERIFIED = "TOOL_VERIFIED"
    HUMAN_CONFIRMED = "HUMAN_CONFIRMED"
    INFERRED = "INFERRED"
    CONFLICTED = "CONFLICTED"
    INVALIDATED = "INVALIDATED"


PROMOTION_ELIGIBLE = frozenset({
    EvidenceCategory.TOOL_VERIFIED,
    EvidenceCategory.HUMAN_CONFIRMED,
})


def may_promote(category: EvidenceCategory | str) -> bool:
    """Fail-closed promotion gate for knowledge records."""
    try:
        return EvidenceCategory(category) in PROMOTION_ELIGIBLE
    except ValueError:
        return False
