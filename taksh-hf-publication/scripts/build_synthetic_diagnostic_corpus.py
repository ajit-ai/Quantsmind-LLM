"""Generate a family-separated synthetic Python corpus for v1.5.0 diagnostics.

The corpus is a *diagnostic fixture*, not a corpus. It exists to answer
"does the training pipeline learn a controlled distribution, and does that
transfer to unseen template families?".

Design:
* Six template families (functions, arithmetic, conditionals, loops, lists,
  exceptions). Training uses four families; the validation split uses the two
  held-out families, so validation is never an exact copy of training and
  measures transfer rather than memorisation.
* Every module is unique: identifiers and constants vary with a fixed seed.
* The output is a v1.2.0-style contract so the v1.3.0 trainer can consume it
  unchanged, with ``dataset_class: synthetic``.

Usage
-----
    python scripts/build_synthetic_diagnostic_corpus.py --out runs/v15_diag
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from data.python_v1.pipeline import build_dataset
from data.python_v1.registry import snapshot_digest

SPDX = "LicenseRef-Taksh-Synthetic"
LICENCE = (
    "Synthetic diagnostic fixture generated by\n"
    "scripts/build_synthetic_diagnostic_corpus.py. Not third-party content.\n"
)

TRAIN_FAMILIES = ("functions", "arithmetic", "conditionals", "loops")
VAL_FAMILIES = ("lists", "exceptions")


def module_source(seed: int, family: str, index: int) -> str:
    rng = random.Random(seed * 1009 + index * 7 + sum(map(ord, family)))
    a = rng.randint(2, 19)
    b = rng.randint(3, 23)
    name = f"{family}_{index}"
    lines = [f'"""Synthetic {family} module {index}."""', "", "import os", ""]
    if family == "functions":
        lines += [
            f"def {name}_total(value):",
            '    """Return a deterministic total."""',
            f"    scaled = value * {a} + {b}",
            "    return scaled + len(os.sep)",
            "",
        ]
    elif family == "arithmetic":
        lines += [
            f"def {name}_area(width, height):",
            '    """Return the area of a rectangle."""',
            f"    return width * height + {a}",
            "",
        ]
    elif family == "conditionals":
        lines += [
            f"def {name}_sign(value):",
            '    """Classify a number."""',
            "    if value > 0:",
            '        return "positive"',
            "    if value < 0:",
            '        return "negative"',
            '    return "zero"',
            "",
        ]
    elif family == "loops":
        lines += [
            f"def {name}_sum(limit):",
            '    """Sum the integers below a limit."""',
            "    total = 0",
            "    for number in range(limit):",
            f"        total += number * {a}",
            "    return total",
            "",
        ]
    elif family == "lists":
        lines += [
            f"def {name}_longest(words):",
            '    """Return the longest word."""',
            "    best = \"\"",
            "    for word in words:",
            "        if len(word) > len(best):",
            "            best = word",
            "    return best",
            "",
        ]
    else:  # exceptions
        lines += [
            f"def {name}_safe(text):",
            '    """Return an upper-cased text, or a marker on failure."""',
            "    try:",
            f"        return text.upper()[:{a}]",
            "    except AttributeError:",
            '        return "unavailable"',
            "",
        ]
    return "\n".join(lines) + "\n"


def build(root: Path, sources: int, modules: int, seed: int, families=TRAIN_FAMILIES,
          prefix: str = "diag") -> list:
    entries = []
    for index in range(sources):
        source_dir = root / f"{prefix}_{index:02d}"
        source_dir.mkdir(parents=True, exist_ok=True)
        (source_dir / "LICENSE").write_text(LICENCE, encoding="utf-8")
        for module_index in range(modules):
            family = families[module_index % len(families)]
            (source_dir / f"m{module_index:02d}.py").write_text(
                module_source(seed, family, index * 100 + module_index), encoding="utf-8"
            )
        snapshot = [
            (p.relative_to(source_dir).as_posix(), hashlib.sha256(p.read_bytes()).hexdigest())
            for p in sorted(source_dir.rglob("*.py"))
        ]
        entries.append(
            {
                "id": f"diag_src_{index:02d}",
                "kind": "local_directory",
                "location": source_dir.name,
                "revision": snapshot_digest(snapshot),
                "project": f"diag_project_{index % 3:02d}",
                "attribution": "Synthetic diagnostic fixture",
                "allowed_extensions": [".py"],
                "excluded_paths": [],
                "license": {
                    "spdx": SPDX,
                    "decision": "approved",
                    "evidence": "LICENSE",
                    "evidence_sha256": hashlib.sha256(
                        (source_dir / "LICENSE").read_bytes()
                    ).hexdigest(),
                },
                "approval": {
                    "status": "approved",
                    "reviewer": "synthetic-fixture",
                    "rationale": "locally generated diagnostic fixture",
                },
            }
        )
    return entries


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Build the v1.5.0 synthetic diagnostic corpus")
    parser.add_argument("--out", required=True)
    parser.add_argument("--sources", type=int, default=12)
    parser.add_argument("--modules", type=int, default=4)
    parser.add_argument("--seed", type=int, default=1500)
    args = parser.parse_args(argv)
    root = Path(args.out).resolve()
    root.mkdir(parents=True, exist_ok=True)
    entries = build(root, args.sources, args.modules, args.seed, TRAIN_FAMILIES, "train")
    heldout_root = root / "heldout_src"
    build(heldout_root, max(2, args.sources // 3), args.modules, args.seed + 1,
          VAL_FAMILIES, "heldout")
    # Held-out completion prefixes: the first lines of unseen-family modules.
    cases = []
    for path in sorted(heldout_root.rglob("m*.py")):
        text = path.read_text(encoding="utf-8")
        lines = text.splitlines(keepends=True)
        prefix = "".join(lines[:3])
        cases.append(
            {
                "case_id": "diag-" + path.parent.name + "-" + path.stem,
                "family": path.stem,
                "prefix": prefix,
                "reference": text,
            }
        )
    (root / "heldout_cases.jsonl").write_text(
        "\n".join(json.dumps(case) for case in cases) + "\n", encoding="utf-8"
    )

    contract = {
        "schema": "quantsmind.python_data_contract/1",
        "version": "synthetic_v15_diagnostic",
        "dataset_class": "synthetic",
        "policy": {
            "default_decision": "deny",
            "allowed_spdx": [SPDX],
            "require_pinned_revision": True,
            "require_license_evidence": True,
        },
        "limits": {
            "max_files": 1000,
            "max_total_bytes": 50_000_000,
            "max_file_bytes": 200_000,
            "max_path_depth": 40,
        },
        "encoding": {"primary": "utf-8", "fallbacks": [], "allow_bom": True},
        "normalization": {"newline": "\n", "strip_bom": True},
        "quality": {
            "min_bytes": 200,
            "max_bytes": 200_000,
            "min_lines": 5,
            "min_unique_token_ratio": 0.10,
            "minified_line_length": 400,
            "minified_average_line_length": 200,
            "max_compression_ratio": 0.08,
            "generated_markers": ["@generated", "do not edit"],
            "excluded_path_patterns": ["(^|/)(vendor|tests?)(/|$)"],
        },
        "dedup": {
            "exact": True,
            "near": True,
            "shingle_size": 8,
            "minhash_perms": 64,
            "minhash_bands": 16,
            "threshold": 0.85,
            "boilerplate_df_ratio": 0.5,
            "max_shingles_per_record": 4000,
            "max_bucket_candidates": 64,
            "group_by_source": True,
            "seed": 120,
        },
        "splits": {
            "proportions": {"train": 0.7, "val": 0.15, "test": 0.15},
            "seed": args.seed,
            "min_groups_per_split": 1,
            "min_records_per_split": 1,
        },
        "benchmarks": {"registry": "benchmarks.yaml", "ngram_size": 13},
        "tokenizer": {"path": "tokenizer/qm_code_bpe_v0.json"},
        "sources": entries,
    }
    (root / "contract.yaml").write_text(
        yaml.safe_dump(contract, sort_keys=True), encoding="utf-8"
    )
    (root / "benchmarks.yaml").write_text(
        yaml.safe_dump(
            {
                "schema": "quantsmind.benchmark_registry/1",
                "version": "synthetic-diagnostic",
                "suites": [
                    {
                        "id": "none_available",
                        "version": "0",
                        "availability": "unavailable",
                        "notes": "no local benchmark copy; nothing was checked",
                    }
                ],
            },
            sort_keys=True,
        ),
        encoding="utf-8",
    )
    manifest = build_dataset(contract_path := root / "contract.yaml", root / "corpus")
    print(f"corpus_class : {manifest['notes']['corpus_class']}")
    print(f"samples kept : {manifest['filtering']['kept']}")
    print(f"splits       : {manifest['splits']['counts']} ready={manifest['splits']['ready']}")
    print(f"manifest     : {root / 'corpus' / 'manifest.json'}")
    print(f"manifest hash: {manifest['manifest_sha256']}")
    print(f"train families: {TRAIN_FAMILIES} | held-out families: {VAL_FAMILIES}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
