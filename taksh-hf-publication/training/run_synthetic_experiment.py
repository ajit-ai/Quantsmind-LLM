"""Run the v1.9.0 bounded synthetic learning experiment.

Pipeline: build the frozen curriculum, prove it is uncontaminated, evaluate
the baseline checkpoint, train S2 on the synthetic training split only, then
evaluate the trained checkpoint with the identical protocol and classify the
result from measured evidence.

Nothing here touches a real corpus, a benchmark, or a production path. The
experimental checkpoint is written to an isolated directory and is never
promoted.
"""

import argparse
import json
import shutil
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

import yaml

from training.synthetic_curriculum import build_curriculum, contamination_report, curriculum_digest
from training.synthetic_eval import classify, evaluate_cases

EVAL_CASES_PER_PARTITION = 8
TRAIN_FAMILIES = ("arithmetic", "conditionals", "list_ops", "string_ops")


def write_corpus(root: Path, partitions) -> Path:
    """Write the synthetic training corpus and build its v1.2.0 manifest.

    The build is cached: a second stage reuses the manifest instead of
    rebuilding it, so every stage fits a bounded subprocess.
    """
    cached = root / "corpus" / "manifest.json"
    if cached.is_file():
        return cached
    from data.python_v1.pipeline import build_dataset
    from data.python_v1.registry import snapshot_digest

    import hashlib

    corpus_root = root / "corpus_src"
    for family in TRAIN_FAMILIES:
        (corpus_root / family).mkdir(parents=True, exist_ok=True)
    sources = []
    for family in TRAIN_FAMILIES:
        cases = [case for case in partitions["train"] if case.family == family]
        directory = corpus_root / family
        for index, case in enumerate(cases):
            (directory / f"case_{index:03d}.py").write_text(
                case.reference, encoding="utf-8"
            )
        entries = [
            (path.relative_to(directory).as_posix(), hashlib.sha256(path.read_bytes()).hexdigest())
            for path in sorted(directory.rglob("*.py"))
        ]
        (directory / "LICENSE").write_text(
            "Synthetic experiment corpus. Generated by "
            "training/synthetic_curriculum.py.\n",
            encoding="utf-8",
        )
        sources.append(
            {
                "id": f"synthetic_{family}",
                "kind": "local_directory",
                "location": str(directory),
                "revision": snapshot_digest(entries),
                "project": f"synthetic_{family}",
                "attribution": "synthetic experiment fixture",
                "allowed_extensions": [".py"],
                "excluded_paths": [],
                "license": {
                    "spdx": "LicenseRef-Taksh-Synthetic",
                    "decision": "approved",
                    "evidence": "LICENSE",
                    "evidence_sha256": hashlib.sha256(
                        (directory / "LICENSE").read_bytes()
                    ).hexdigest(),
                },
                "approval": {
                    "status": "approved",
                    "reviewer": "synthetic-experiment",
                    "rationale": "synthetic-only experiment corpus, not a production source",
                },
            }
        )
    contract = {
        "schema": "quantsmind.python_data_contract/1",
        "version": "synthetic_v19",
        "dataset_class": "synthetic",
        "policy": {
            "default_decision": "deny",
            "allowed_spdx": ["LicenseRef-Taksh-Synthetic"],
            "require_pinned_revision": True,
            "require_license_evidence": True,
        },
        "limits": {
            "max_files": 1000,
            "max_total_bytes": 50_000_000,
            "max_file_bytes": 200_000,
            "max_path_depth": 40,
        },
        "encoding": {"primary": "utf-8", "fallbacks": []},
        "normalization": {"newline": "\n", "strip_bom": True},
        "quality": {
            "min_bytes": 20,
            "max_bytes": 200_000,
            "min_lines": 2,
            "min_unique_token_ratio": 0.05,
        },
        "dedup": {
            "exact": True,
            "near": False,
            "group_by_source": True,
        },
        "splits": {
            "proportions": {"train": 0.5, "val": 0.25, "test": 0.25},
            "seed": 20261021,
            "min_groups_per_split": 1,
            "min_records_per_split": 1,
        },
        "benchmarks": {},
        "tokenizer": {"path": "tokenizer/qm_code_bpe_v0.json"},
        "sources": sources,
    }
    contract_path = root / "contract.yaml"
    contract_path.write_text(yaml.safe_dump(contract, sort_keys=True), encoding="utf-8")
    manifest = build_dataset(contract_path, root / "corpus")
    return root / "corpus" / "manifest.json"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="v1.9.0 synthetic learning experiment")
    parser.add_argument("--work", required=True)
    parser.add_argument("--max-steps", type=int, default=30)
    parser.add_argument("--seed", type=int, default=20261021)
    parser.add_argument("--baseline", default="runs/m7_pretrain/checkpoint_last.pt")
    parser.add_argument("--budget", type=int, default=96)
    parser.add_argument("--skip-training", action="store_true")
    parser.add_argument(
        "--stage",
        default="all",
        choices=["all", "baseline", "train", "evaluate"],
        help="run one stage so every step fits a bounded subprocess",
    )
    parser.add_argument("--eval-budget", type=int, default=64)
    parser.add_argument("--context-length", type=int, default=256)
    parser.add_argument("--grad-accum", type=int, default=4)
    args = parser.parse_args(argv)

    root = Path(args.work).resolve()
    root.mkdir(parents=True, exist_ok=True)
    started = time.time()

    partitions = build_curriculum(args.seed)
    digest = curriculum_digest(partitions)
    cache = root / "contamination.json"
    if cache.is_file():
        contamination = json.loads(cache.read_text(encoding="utf-8"))
    else:
        contamination = contamination_report(partitions)
        cache.write_text(json.dumps(contamination, indent=2), encoding="utf-8")
    print("curriculum digest:", digest)
    print("contamination:", contamination["verdict"], contamination["violation_count"])
    if contamination["contaminated"]:
        print("REFUSED: the synthetic evaluation is contaminated")
        return 2

    manifest_path = write_corpus(root, partitions)
    print("corpus manifest:", manifest_path)

    from tokenizers import Tokenizer

    from serving.local_inference import load_model

    tokenizer = Tokenizer.from_file(str(REPO / "tokenizer" / "qm_code_bpe_v0.json"))
    eval_sets = {
        name: partitions[name][:EVAL_CASES_PER_PARTITION]
        for name in ("A", "B", "C")
    }

    baseline_path = root / "baseline.json"
    if args.stage in ("all", "baseline"):
        baseline_model, _ = load_model(str(REPO / args.baseline), "cpu")
        baseline_started = time.time()
        baseline = {}
        for name, cases in eval_sets.items():
            result = evaluate_cases(
                baseline_model, tokenizer, cases, budget=args.eval_budget, temperature=0.0
            )
            baseline[name] = result["aggregate"]
            print("baseline", name, json.dumps(result["aggregate"])[:200])
        print("baseline eval seconds", round(time.time() - baseline_started, 1))
        payload = {"baseline": baseline, "curriculum_digest": digest}
        baseline_path.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
        if args.stage == "baseline":
            return 0
    if not baseline_path.exists():
        print("REFUSED: the baseline stage must run first")
        return 2
    baseline = json.loads(baseline_path.read_text(encoding="utf-8"))["baseline"]

    train_config = {
        "schema": "quantsmind.train_config/1",
        "mode": "synthetic",
        "run": {
            "name": "v19-synthetic",
            "model_config": "configs/model/code_m3_9m.yaml",
            "seed": args.seed,
        },
        "data": {
            "manifest": "corpus/manifest.json",
            "tokenizer": "tokenizer/qm_code_bpe_v0.json",
            "context_length": args.context_length,
            "sequence_policy": "document",
            "append_eos": True,
            "allow_cross_document": False,
        },
        "optimizer": {
            "type": "adamw",
            "lr_peak": 3.0e-3,
            "warmup_steps": 2,
            "min_lr_ratio": 0.1,
            "beta1": 0.9,
            "beta2": 0.95,
            "weight_decay": 0.1,
            "grad_clip": 1.0,
        },
        "batch": {"micro_batch_size": 1, "grad_accum_steps": args.grad_accum,
                  "shuffle": True},
        "precision": {"device": "cpu", "dtype": "float32"},
        "training": {
            "max_steps": args.max_steps,
            "max_tokens": 500_000,
            "max_wall_seconds": 900,
            "checkpoint_every_steps": max(1, args.max_steps),
            "eval_every_steps": max(1, args.max_steps // 2),
            "val_batches": 2,
            "output_dir": "train_out",
        },
        "limits": {"max_checkpoints": 2, "max_output_bytes": 200_000_000},
    }
    config_path = root / "train_config.yaml"
    config_path.write_text(yaml.safe_dump(train_config, sort_keys=True), encoding="utf-8")

    from training.train import run_training

    if args.stage == "evaluate":
        run_manifest = json.loads(
            (root / "train_manifest.json").read_text(encoding="utf-8")
        )
    else:
        train_started = time.time()
        run_manifest = run_training(str(config_path))
        (root / "train_manifest.json").write_text(
            json.dumps(run_manifest, indent=2, default=str), encoding="utf-8"
        )
    train_seconds = 0.0 if args.stage == "evaluate" else round(time.time() - train_started, 1)
    metrics = run_manifest["training"]["metrics"]
    print("train seconds", train_seconds, "metrics", json.dumps(metrics)[:240])

    checkpoint = root / "train_out" / "checkpoint_last.pt"
    if not checkpoint.is_file():
        print("REFUSED: the training stage must run first")
        return 2
    trained_model, _ = load_model(str(checkpoint), "cpu")
    trained = {}
    for name, cases in eval_sets.items():
        result = evaluate_cases(
            trained_model, tokenizer, cases, budget=args.budget, temperature=0.0
        )
        trained[name] = result["aggregate"]
        print("trained", name, json.dumps(result["aggregate"])[:200])

    loss_delta = None
    if metrics.get("initial_train_loss") is not None and metrics.get("final_train_loss") is not None:
        loss_delta = metrics["final_train_loss"] - metrics["initial_train_loss"]
    verdict = classify(baseline, trained, loss_delta=loss_delta)
    print("CLASSIFICATION:", verdict["verdict"], "|", verdict["reason"])

    report = {
        "schema": "quantsmind.v19_experiment/1",
        "curriculum_digest": digest,
        "contamination": contamination,
        "baseline": baseline,
        "trained": trained,
        "training": {
            "steps": run_manifest["training"]["steps_completed"],
            "tokens": run_manifest["training"]["tokens_processed"],
            "seconds": train_seconds,
            "metrics": metrics,
        },
        "classification": verdict,
        "checkpoint": str(checkpoint),
        "baseline_checkpoint": args.baseline,
        "total_seconds": round(time.time() - started, 1),
    }
    (root / "experiment_report.json").write_text(
        json.dumps(report, indent=2, default=str), encoding="utf-8"
    )
    print("report:", root / "experiment_report.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
